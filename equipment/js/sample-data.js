function seedAt(dayOffset, h, m) {
  const d = new Date(); d.setDate(d.getDate() + dayOffset); d.setHours(h, m, 0, 0);
  if (dayOffset === 0) return new Date(Math.min(d.getTime(), Date.now() - (24 * 60 - (h * 60 + m)) * 1000)).toISOString();
  return d.toISOString();
}
